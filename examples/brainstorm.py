def generate_idea(agent_id, topic, sync_r, mood):
    """
    "LLM" адаптер: выбирает идею из пула на основе состояния.
    Чем выше sync и mood — тем смелее идея.
    """
    role = ROLES[agent_id]["name"]
    pool = IDEA_POOLS[role]

    # При высокой синхронизации и позитивном настроении — выбираем смелые идеи
    if sync_r > 0.8 and mood > 0.5:
        idx = random.randint(0, len(pool) - 1)
    else:
        # При низкой синхронизации — консервативные (первые в списке)
        idx = random.randint(0, min(1, len(pool) - 1))

    idea = pool[idx]
    return f"[{role}] {idea}"


def score_idea(idea_text, sync_r, mood, energy):
    """
    Оценка идеи: чем выше синхронизация системы при генерации — тем выше балл.
    """
    base = sync_r * 100  # 0-100
    mood_bonus = max(0, mood) * 20  # +0-20
    energy_penalty = min(energy * 5, 20)  # штраф за перегрузку
    return base + mood_bonus - energy_penalty


